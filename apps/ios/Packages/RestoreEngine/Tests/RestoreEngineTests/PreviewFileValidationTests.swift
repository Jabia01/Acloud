import XCTest
import Foundation
import CryptoKit
@testable import RestoreEngine
final class PreviewFileValidationTests:XCTestCase {
 private func item(_ id:UUID,bytes:Data)->RestoreItem {
  RestoreItem(accountID:UUID(),libraryID:UUID(),evidence:RestoreEvidence(id:UUID(),cloudVersionId:String(repeating:"a",count:64),mediaType:"image",expectedSize:bytes.count,expectedSha256:SHA256.hash(data:bytes).map{String(format:"%02x",$0)}.joined(),resourcePolicy:"VERIFIED_PREVIEW_RESOURCE"),id:id)
 }
 func testPreviewDirectoryHintAndAliasVerifySameBytes()throws {
  let root=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString,isDirectory:true)
  try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true);defer{try? FileManager.default.removeItem(at:root)}
  let real=root.appendingPathComponent("real",isDirectory:true),alias=root.appendingPathComponent("alias",isDirectory:true)
  try FileManager.default.createDirectory(at:real,withIntermediateDirectories:true)
  try FileManager.default.createSymbolicLink(at:alias,withDestinationURL:real)
  let files=try RestoreFiles(directory:alias.appendingPathComponent("Preview-generated",isDirectory:true)),id=UUID(),bytes=Data("generated preview bytes".utf8)
  try bytes.write(to:files.url(id));try files.verify(item(id,bytes:bytes))
  let aliasFile=alias.appendingPathComponent("Preview-generated",isDirectory:true).appendingPathComponent(id.uuidString+".bin")
  XCTAssertNoThrow(try files.validate(aliasFile))
  try Data(repeating:0,count:bytes.count).write(to:files.url(id))
  XCTAssertThrowsError(try files.verify(item(id,bytes:bytes))){XCTAssertEqual($0 as? RestoreFailure,.integrity)}
 }
 func testExternalFileAndSymbolicLinksRemainRejected()throws {
  let root=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
  try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true);defer{try? FileManager.default.removeItem(at:root)}
  let files=try RestoreFiles(directory:root.appendingPathComponent("preview",isDirectory:true)),id=UUID(),bytes=Data("generated bytes".utf8),outside=root.appendingPathComponent("outside.bin")
  try bytes.write(to:outside)
  XCTAssertThrowsError(try files.validate(outside))
  try FileManager.default.createSymbolicLink(at:files.url(id),withDestinationURL:outside)
  XCTAssertThrowsError(try files.verify(item(id,bytes:bytes))){XCTAssertEqual($0 as? RestoreFailure,.storage)}
  try FileManager.default.removeItem(at:files.url(id))
  let other=files.directory.appendingPathComponent("other.bin");try bytes.write(to:other)
  try FileManager.default.createSymbolicLink(at:files.url(id),withDestinationURL:other)
  XCTAssertThrowsError(try files.verify(item(id,bytes:bytes)))
 }
}
